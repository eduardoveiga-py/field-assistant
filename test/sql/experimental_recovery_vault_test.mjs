const { PGlite } = await import(process.env.PGLITE_MODULE ?? '@electric-sql/pglite');
import { readFileSync } from 'node:fs';
import assert from 'node:assert/strict';
const db = new PGlite();
const alice = '11111111-1111-4111-8111-111111111111';
const bob = '22222222-2222-4222-8222-222222222222';
const box = {v: 1, algorithm: 'A256GCM', nonce: 'a'.repeat(16), ciphertext: 'YQ==', tag: 'b'.repeat(24)};
const marker = {version: 1, vaultId: 'a'.repeat(32), envelope: box};
await db.exec(`CREATE ROLE authenticated; CREATE ROLE anon; CREATE SCHEMA auth;
 CREATE FUNCTION auth.uid() RETURNS uuid LANGUAGE sql AS $$ SELECT NULLIF(current_setting('request.jwt.claim.sub', true), '')::uuid $$;
 GRANT USAGE ON SCHEMA auth TO authenticated, anon; GRANT EXECUTE ON FUNCTION auth.uid() TO authenticated, anon;`);
await db.exec(readFileSync(new URL('../../supabase/migrations/20261116190100_experimental_recovery_vault.sql', import.meta.url), 'utf8'));
await db.exec(`SET ROLE authenticated; SELECT set_config('request.jwt.claim.sub', '${alice}', false);`);
const create = async m => (await db.query('select public.experimental_recovery_vault_create($1::jsonb) as result', [JSON.stringify(m)])).rows[0].result;
const read = async () => (await db.query('select owner_id, marker from public.experimental_recovery_vaults')).rows;
assert.deepEqual(await create(marker), {success: true});
assert.deepEqual(await create({...marker, vaultId: 'b'.repeat(32)}), {success: false, conflict: true});
assert.deepEqual((await read())[0].marker, marker);
await assert.rejects(create({...marker, phrase: 'secret'}));
await assert.rejects(create({...marker, envelope: {...box, ciphertext: 'x'.repeat(4097)}}));
await assert.rejects(db.query('update public.experimental_recovery_vaults set marker = $1::jsonb', [JSON.stringify(marker)]));
await assert.rejects(db.query('delete from public.experimental_recovery_vaults'));
await db.exec(`SELECT set_config('request.jwt.claim.sub', '${bob}', false);`);
assert.deepEqual(await read(), []);
assert.deepEqual(await create({...marker, vaultId: 'b'.repeat(32)}), {success: true});
assert.equal((await read())[0].owner_id, bob);
await db.exec(`SELECT set_config('request.jwt.claim.sub', '', false);`);
await assert.rejects(create(marker));
await db.exec('RESET ROLE; SET ROLE anon;');
await assert.rejects(create(marker));
await assert.rejects(read());
console.log('PASS: vault create-only, format validation, isolation and denied direct writes');
await db.close();
